"""Usage: python3 port.py <Plates BodyMusclePaths.swift> <InjectionSitePaths.swift>

Ports Plates' BodyMusclePaths.swift to InjectionSitePaths.swift, tagging
the paths that are injection sites and leaving the rest as outline."""
import re, sys
src = open(sys.argv[1]).read()
front_s = src.index("static let front:"); back_s = src.index("static let back:"); end = src.index("static let frontParsed")
FRONT_W, BACK_W = 652, 665

entry = re.compile(r'MusclePathData\(muscle: (nil|\.[a-zA-Z]+), d: "([^"]+)"\)')
def bbox(d):
    """Bounding box of an absolute-command SVG path."""
    toks = re.findall(r'[MLHVCZmlhvcz]|-?\d*\.?\d+(?:e-?\d+)?', d)
    xs=[];ys=[];cmd=None;cur=[0,0];nums=[]
    def flush():
        nonlocal nums
        if cmd is None: return
        if cmd in "MLC":
            for i in range(0,len(nums)-1,2):
                xs.append(nums[i]); ys.append(nums[i+1]); cur[:]=[nums[i],nums[i+1]]
        elif cmd=='H':
            for n in nums: xs.append(n); ys.append(cur[1]); cur[0]=n
        elif cmd=='V':
            for n in nums: ys.append(n); xs.append(cur[0]); cur[1]=n
        nums=[]
    for t in toks:
        if t.isalpha():
            flush(); cmd=t
            if cmd.islower(): raise SystemExit("relative cmd")
        else: nums.append(float(t))
    flush()
    return min(xs),min(ys),max(xs),max(ys)

def site(view, muscle, box):
    x0, y0, x1, y1 = box
    cx = (x0 + x1) / 2
    if view == "front":
        # Facing us: the viewer's right is the person's left.
        side = "Left" if cx > FRONT_W / 2 else "Right"
        if muscle == ".core": return "abdomen" + side
        if muscle == ".legs" and y0 >= 600 and y1 <= 1110: return "thigh" + side
    else:
        side = "Right" if cx > BACK_W / 2 else "Left"
        if muscle == ".triceps": return "arm" + side
        if muscle == ".hips": return "glute" + side
    return None

lines, counts = [], {}
for view, (a, b) in {"front": (front_s, back_s), "back": (back_s, end)}.items():
    lines.append(f"    static let {view}: [BodyPath] = [")
    for m in entry.finditer(src[a:b]):
        s = site(view, m.group(1), bbox(m.group(2)))
        counts[s] = counts.get(s, 0) + 1
        tag = f".{s}" if s else "nil"
        lines.append(f'        BodyPath(site: {tag}, d: "{m.group(2)}"),')
    lines.append("    ]\n")

header = '''import SwiftUI

/// One SVG `<path>` of the body outline, and the injection site it belongs
/// to (`nil` for the parts that are only drawn, never picked).
struct BodyPath {
    var site: InjectionSite?
    var d: String
}

/// Front and back body outlines for the injection-site map, from the same
/// artwork as Plates' body silhouette. Generated by
/// `Tools/BodyMap/port.py`, so edit the artwork there rather than here.
enum InjectionSitePaths {
    static let frontViewBox = CGSize(width: 652, height: 1627)
    static let backViewBox = CGSize(width: 665, height: 1628)

'''
footer = '''    /// Parsed once and kept for the rest of the process.
    static let frontParsed: [(site: InjectionSite?, path: Path)] =
        front.map { (site: $0.site, path: SVGPathParser.path(from: $0.d)) }
    static let backParsed: [(site: InjectionSite?, path: Path)] =
        back.map { (site: $0.site, path: SVGPathParser.path(from: $0.d)) }
}
'''
open(sys.argv[2], "w").write(header + "\n".join(lines) + footer)
print({k: v for k, v in counts.items()})
